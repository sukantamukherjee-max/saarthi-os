import { useEffect, useMemo, useState } from 'react';
import { sx } from '../components/sx';

export default function RecommendationsPage({ vm }: { vm: any }) {
  const rc = vm.rc;
  const [narrated, setNarrated] = useState<Record<string, string>>({});
  const [narratedKey, setNarratedKey] = useState<string | null>(null);
  const [narrating, setNarrating] = useState(false);
  const [narrateFailed, setNarrateFailed] = useState(false);

  const flatItems = useMemo(() => rc.groups.flatMap((g: any) => g.items), [rc.groups]);
  const itemsKey = useMemo(() => flatItems.map((i: any) => i.title + '|' + i.body).join('~'), [flatItems]);

  useEffect(() => {
    if (!rc.mAI || itemsKey === narratedKey) return;
    let cancelled = false;
    setNarrating(true);
    setNarrateFailed(false);
    const payload = { items: flatItems.map((i: any) => ({ title: i.title, body: i.body, action: i.action, impact: i.impact, risk: i.risk })), context: rc.aiContext };
    fetch('/.netlify/functions/narrate-recommendation', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload),
    })
      .then((r) => (r.ok ? r.json() : Promise.reject(new Error('narration request failed'))))
      .then((data) => {
        if (cancelled) return;
        const map: Record<string, string> = {};
        (data.items || []).forEach((it: any, idx: number) => {
          const orig = payload.items[idx];
          if (orig && it?.body) map[orig.title] = it.body;
        });
        setNarrated(map);
        setNarratedKey(itemsKey);
      })
      .catch(() => { if (!cancelled) setNarrateFailed(true); })
      .finally(() => { if (!cancelled) setNarrating(false); });
    return () => { cancelled = true; };
  }, [rc.mAI, itemsKey, narratedKey, flatItems, rc.aiContext]);

  return (
    <div style={sx('animation:pwFade .35s ease both')}>
      <div style={sx('display:flex;align-items:flex-end;justify-content:space-between;gap:20px;flex-wrap:wrap;margin-bottom:24px')}>
        <div>
          <h1 style={sx('font-size:34px;font-weight:400;letter-spacing:-.02em;margin:0 0 4px')}>Recommendations</h1>
          <p style={sx('font-size:13px;color:color-mix(in srgb,var(--color-text) 55%,transparent);margin:0')}>Model-generated. Nothing here is issued where material data is missing.</p>
        </div>
        <div className="seg">
          <label className="seg-opt"><input type="radio" name="mode" value="Data" checked={rc.mData} onChange={vm.h.mode} />Data</label>
          <label className="seg-opt"><input type="radio" name="mode" value="Advisor" checked={rc.mAdvisor} onChange={vm.h.mode} />Advisor</label>
          <label className="seg-opt"><input type="radio" name="mode" value="Strong Advisor" checked={rc.mStrong} onChange={vm.h.mode} />Strong advisor</label>
          <label className="seg-opt"><input type="radio" name="mode" value="AI Advisor" checked={rc.mAI} onChange={vm.h.mode} />AI Advisor</label>
        </div>
      </div>

      {rc.mAI && (
        <div style={sx('font-size:11px;opacity:.55;margin:-14px 0 20px')}>
          {narrating ? 'AI is writing a personalized narrative for each item…' : narrateFailed ? 'AI narration unavailable right now — showing the standard Advisor wording instead.' : 'Narrated by AI from the model’s own computed numbers — no figure here was generated by the AI itself.'}
        </div>
      )}

      {rc.groups.map((g: any, gi: number) => (
        <div key={gi} style={sx('margin-bottom:26px')}>
          <div style={sx('display:flex;align-items:baseline;gap:12px;margin-bottom:12px')}>
            <h4 style={sx('margin:0;font-size:20px;font-weight:600')}>{g.name}</h4>
            <span style={sx('font-size:11px;opacity:.5')}>{g.note}</span>
            <div style={sx('flex:1;height:1px;background:var(--color-divider)')}></div>
          </div>
          <div style={sx('display:grid;grid-template-columns:repeat(auto-fit,minmax(300px,1fr));gap:14px')}>
            {g.items.map((r: any, ri: number) => (
              <div key={ri} className="card" style={sx('padding:17px 19px;gap:9px')}>
                <div style={sx('display:flex;align-items:center;gap:8px;flex-wrap:wrap')}>
                  <span style={sx(r.actionStyle)}>{r.action}</span>
                  <span style={sx('font-size:10.5px;opacity:.55')}>{r.conf} confidence</span>
                  <span style={sx('margin-left:auto;font-size:10px;opacity:.42')}>{r.fresh}</span>
                </div>
                <div style={sx('font-family:var(--font-heading);font-size:16.5px;font-weight:600;line-height:1.25')}>{r.title}</div>
                <div style={sx('font-size:13px;color:color-mix(in srgb,var(--color-text) 68%,transparent)')}>{rc.mAI && narrated[r.title] ? narrated[r.title] : r.body}</div>
                <div style={sx('display:flex;gap:14px;border-top:1px solid var(--color-divider);padding-top:8px;font-size:11.5px;flex-wrap:wrap')}>
                  <span style={sx('opacity:.55')}>Impact</span><span style={sx('font-variant-numeric:tabular-nums')}>{r.impact}</span>
                  <span style={sx('opacity:.55;margin-left:auto')}>Risk if ignored</span><span>{r.risk}</span>
                </div>
              </div>
            ))}
          </div>
        </div>
      ))}

      <div className="card" style={sx('padding:18px 20px;gap:8px;border-style:dashed')}>
        <div style={sx('font-size:10px;letter-spacing:.1em;text-transform:uppercase;color:var(--color-accent)')}>Withheld</div>
        <div style={sx('font-size:13px;color:color-mix(in srgb,var(--color-text) 70%,transparent)')}>{rc.withheld}</div>
      </div>
    </div>
  );
}
